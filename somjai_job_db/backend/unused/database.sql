CREATE TYPE marital_status_enum AS ENUM (
    'โสด','สมรสจดทะเบียน','สมรสไม่จดทะเบียน','หม้าย','หย่าร้าง'
);
CREATE TYPE education_enum AS ENUM (
    'ป.6','ม.3','ม.6','ปวช.','ปวส.','ปริญญาตรี','ปริญญาโท'
);
CREATE TYPE app_status_enum AS ENUM (
    'รับเรื่อง','สัมภาษณ์','ผ่าน','ไม่ผ่าน','สำรอง'
);

