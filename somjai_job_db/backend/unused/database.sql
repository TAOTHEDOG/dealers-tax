CREATE TABLE IF NOT EXISTS provinces (
    id        SMALLINT PRIMARY KEY,
    name_th   VARCHAR(100) NOT NULL,
    name_en   VARCHAR(100),
    region    VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS districts (
    id          INTEGER PRIMARY KEY,
    province_id SMALLINT NOT NULL REFERENCES provinces(id) ON UPDATE CASCADE ON DELETE CASCADE,
    name_th     VARCHAR(100) NOT NULL,
    name_en     VARCHAR(100)
);
CREATE INDEX IF NOT EXISTS idx_district_province ON districts(province_id);

CREATE TABLE IF NOT EXISTS subdistricts (
    id          BIGINT PRIMARY KEY,
    district_id INTEGER NOT NULL REFERENCES districts(id) ON UPDATE CASCADE ON DELETE CASCADE,
    name_th     VARCHAR(100) NOT NULL,
    name_en     VARCHAR(100),
    zipcode     CHAR(5) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_subdistrict_district ON subdistricts(district_id);
CREATE INDEX IF NOT EXISTS idx_subdistrict_zip      ON subdistricts(zipcode);

