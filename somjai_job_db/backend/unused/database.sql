    nickname                VARCHAR(100) NOT NULL,
    phone                   VARCHAR(20)  NOT NULL,
    birth_date              DATE         NOT NULL,
    age                     SMALLINT,
    height_cm               SMALLINT,
    weight_kg               SMALLINT,
    birth_province          VARCHAR(100),

    -- Section 3
    school_name             VARCHAR(200),
    education_level         education_enum,
    major                   VARCHAR(200),

    -- Section 4
    marital_status          marital_status_enum NOT NULL,
    children_count          SMALLINT DEFAULT 0,
