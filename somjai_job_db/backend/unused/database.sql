CREATE OR REPLACE VIEW v_applications_full AS
SELECT
    a.id, a.submitted_at, a.status,
    a.full_name, a.nickname, a.phone, a.birth_date, a.age,
    a.position1, a.position2, a.expected_salary,
    -- ที่อยู่ปัจจุบัน
    a.cur_house_no, a.cur_village, a.cur_road, a.cur_soi,
    cs.name_th AS cur_subdistrict,
    cd.name_th AS cur_district,
    cp.name_th AS cur_province,
    a.cur_postal,
    -- ที่อยู่ทะเบียนบ้าน
    a.reg_house_no, a.reg_village, a.reg_road, a.reg_soi,
    rs.name_th AS reg_subdistrict,
    rd.name_th AS reg_district,
    rp.name_th AS reg_province,
    a.reg_postal,
    -- ทักษะ
    a.eng_speaking, a.eng_writing, a.ms_word, a.ms_excel, a.ms_ppt,
    -- ขับขี่
    a.can_drive_car, a.car_gear, a.has_car_license, a.has_own_car,
    a.can_drive_moto, a.has_moto_license, a.has_own_moto
FROM applications a
LEFT JOIN subdistricts cs ON cs.id = a.cur_subdistrict_id
LEFT JOIN districts    cd ON cd.id = a.cur_district_id
LEFT JOIN provinces    cp ON cp.id = a.cur_province_id
LEFT JOIN subdistricts rs ON rs.id = a.reg_subdistrict_id
LEFT JOIN districts    rd ON rd.id = a.reg_district_id
LEFT JOIN provinces    rp ON rp.id = a.reg_province_id;

CREATE OR REPLACE VIEW v_stats_by_province AS
SELECT
    cp.name_th                                          AS province,
    COUNT(*)                                            AS total,
    SUM(CASE WHEN a.status = 'ผ่าน' THEN 1 ELSE 0 END) AS passed
FROM applications a
LEFT JOIN provinces cp ON cp.id = a.cur_province_id
GROUP BY cp.id, cp.name_th
ORDER BY total DESC;

